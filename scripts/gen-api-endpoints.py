"""Regenerates src/lib/api/endpoints.ts from docs/api/toon-central.postman.json.

Run from the project root:  python3 scripts/gen-api-endpoints.py
"""
import json
import re
from collections import Counter

SOURCE = "docs/api/toon-central.postman.json"
TARGET = "src/lib/api/endpoints.ts"

# GET requests that still do something: count a view, like, follow, send an email, verify an account.
ACTION_GET = re.compile(
    r"/(view|like|dislike|subscribe|add-to-favourite|follow|unfollow|infinite-view)$|resend-verification-code|onboard/verify"
)


def requests(items, folders):
    for item in items:
        if "item" in item:
            yield from requests(item["item"], folders + [item["name"]])
        else:
            yield folders, item


def area_of(folders, path):
    top = folders[0] if folders else ""
    if top == "Not for Use" or path.startswith("http"):
        return None
    if top == "Onboarding":
        return "money" if re.search(r"plans|credit-points|comic-coin|mobile-operators", path) else "accounts"
    if top == "Landing Page":
        if re.search(r"/(like|dislike|subscribe|add-to-favourite)$|favourites|subscribed|viewed", path):
            return "readerActions"
        if "unlock-task" in path or "coupons" in path:
            return "money"
        return "reading"
    if top == "Authenticated":
        sub = folders[1] if len(folders) > 1 else ""
        if sub == "Creators":
            return "studio"
        if sub in ("Comments", "Follow and Unfollow"):
            return "readerActions"
        if sub in ("Subscription & Comic Coin", "Histories") or path == "wallet":
            return "money"
        return "readerActions" if path == "user-likes" else "accounts"
    return "reading"


def main():
    collection = json.load(open(SOURCE))
    rows, seen = [], set()
    for folders, item in requests(collection["item"], []):
        request = item["request"]
        url = request.get("url")
        raw = url if isinstance(url, str) else (url or {}).get("raw", "")
        path = raw.replace("{{baseUrl}}", "").split("?")[0].lstrip("/")
        method = request.get("method", "GET")
        area = area_of(folders, path)
        if not area or (method, path) in seen:
            continue
        seen.add((method, path))
        rows.append({
            "name": " / ".join(folders[1:] + [item["name"]]),
            "method": method,
            "path": path,
            "area": area,
            "auth": any(h.get("key", "").lower() == "authorization" for h in request.get("header", [])),
            "example": bool(item.get("response")),
            "changesData": method != "GET" or bool(ACTION_GET.search(path)),
        })

    lines = [
        "// GENERATED by scripts/gen-api-endpoints.py from docs/api/toon-central.postman.json (the backend's",
        "// published Postman collection). Every endpoint the frontend can use, grouped by the area that switches",
        "// it from mock to live. `changesData`: calling it does something (including the GETs that like, follow,",
        "// count a view or send an email). Regenerate when the collection changes; don't edit by hand.",
        "",
        'import type { ApiArea } from "./config";',
        "",
        'export type Endpoint = { name: string; method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE"; path: string; area: ApiArea; auth: boolean; example: boolean; changesData: boolean };',
        "",
        "export const ENDPOINTS: Endpoint[] = [",
    ]
    for row in rows:
        fields = ", ".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in row.items())
        lines.append(f"  {{{fields}}},")
    lines += ["];", ""]
    open(TARGET, "w").write("\n".join(lines))
    print(len(rows), "endpoints", dict(Counter(r["area"] for r in rows)))


if __name__ == "__main__":
    main()
